<?php

namespace App\Http\Controllers;

use App\Http\Requests\StoreReminderRuleRequest;
use App\Http\Requests\UpdateReminderRuleRequest;
use App\Models\AuditLog;
use App\Models\ReminderRule;
use App\Models\ReminderTemplate;
use Illuminate\Http\RedirectResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;
use Illuminate\View\View;

class ReminderRuleController extends Controller
{
    public function index(): View
    {
        return view('reminders.rules', [
            'rules' => ReminderRule::query()->with('template')->orderBy('name')->paginate(20),
        ]);
    }

    public function store(StoreReminderRuleRequest $request): RedirectResponse
    {
        $data = $request->validated();
        DB::transaction(function () use ($data, $request): void {
            $template = ReminderTemplate::query()->create([
                'name' => $data['template_name'],
                'channel' => 'in_app',
                'language' => $data['language'] ?? null,
                'body' => $data['template_body'],
                'is_active' => true,
            ]);
            $rule = ReminderRule::query()->create([
                'name' => $data['name'],
                'trigger_type' => $data['trigger_type'],
                'offset_days' => $data['offset_days'],
                'template_id' => $template->id,
                'channel' => 'in_app',
                'is_active' => true,
                'created_by' => $request->user()->id,
            ]);
            $this->audit($request, 'reminder.rule_created', $rule, null, $this->auditValues($rule));
        });

        return redirect()->route('reminders.rules.index')->with('status', 'Reminder rule saved. Tasks will be generated by the scheduled reminder command.');
    }

    public function update(UpdateReminderRuleRequest $request, ReminderRule $reminderRule): RedirectResponse
    {
        $data = $request->validated();
        DB::transaction(function () use ($data, $request, $reminderRule): void {
            $rule = ReminderRule::query()->lockForUpdate()->with('template')->findOrFail($reminderRule->id);
            $before = $this->auditValues($rule);
            $rule->update([
                'name' => $data['name'],
                'trigger_type' => $data['trigger_type'],
                'offset_days' => $data['offset_days'],
                'is_active' => $data['is_active'],
            ]);
            $rule->template?->update([
                'name' => $data['template_name'],
                'body' => $data['template_body'],
                'language' => $data['language'] ?? null,
            ]);
            $this->audit($request, 'reminder.rule_updated', $rule, $before, $this->auditValues($rule->fresh()));
        });

        return redirect()->route('reminders.rules.index')->with('status', 'Reminder rule and template updated.');
    }

    /** @return array<string, mixed> */
    private function auditValues(ReminderRule $rule): array
    {
        return [
            ...$rule->only(['name', 'trigger_type', 'offset_days', 'template_id', 'channel', 'is_active']),
            'template_name' => $rule->template?->name,
            'template_body' => $rule->template?->body,
            'template_language' => $rule->template?->language,
        ];
    }

    /** @param array<string, mixed>|null $before
     * @param  array<string, mixed>|null  $after
     */
    private function audit(Request $request, string $action, ReminderRule $rule, ?array $before, ?array $after): void
    {
        AuditLog::record($request, $action, $rule, $before, $after);
    }
}
